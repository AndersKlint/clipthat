import 'dart:async';
import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:path/path.dart' as p;

import '../models/clip_job.dart';
import '../models/clip_request.dart';
import '../models/subtitle_track.dart';
import '../services/subtitle_catalog.dart';
import '../services/bundled_tools.dart';
import '../services/clip_pipeline.dart';
import '../services/output_folder_preferences.dart';

class ClipController extends ChangeNotifier {
  late final SubtitleCatalog _subtitleCatalog = SubtitleCatalog(_bundledTools);
  String? _subtitleVideoId;
  List<SubtitleTrack> _subtitleTracks = const [];
  List<SubtitleTrack> _selectedSubtitleTracks = const [];
  Future<void>? _subtitleLoad;
  bool _subtitlesLoaded = false;
  String? _subtitleError;
  int _subtitleRevision = 0;
  bool _includeAutoGeneratedSubtitles = false;

  bool get includeAutoGeneratedSubtitles => _includeAutoGeneratedSubtitles;
  List<SubtitleTrack> get subtitleTracks => List.unmodifiable(
        _subtitleTracks.where(_isSubtitleVisible),
      );
  List<SubtitleTrack> get selectedSubtitleTracks => List.unmodifiable(
        _selectedSubtitleTracks.where(_isSubtitleVisible),
      );
  bool get subtitlesLoading => _subtitleLoad != null;
  bool get subtitlesLoaded => _subtitlesLoaded;
  String? get subtitleError => _subtitleError;

  bool _isSubtitleVisible(SubtitleTrack track) =>
      _includeAutoGeneratedSubtitles || !track.isAutomatic;

  void setIncludeAutoGeneratedSubtitles(bool value) {
    if (_includeAutoGeneratedSubtitles == value) return;
    _includeAutoGeneratedSubtitles = value;
    _notify();
  }

  void setSubtitleSource(String text) {
    String? id;
    try {
      id = YouTubeLink.parse(text).videoId;
    } on FormatException {
      id = null;
    }
    if (id == _subtitleVideoId) return;
    _subtitleRevision++;
    _subtitleVideoId = id;
    _subtitleTracks = const [];
    _selectedSubtitleTracks = const [];
    _subtitleLoad = null;
    _subtitlesLoaded = false;
    _subtitleError = null;
    _notify();
  }

  void selectSubtitleTracks(List<SubtitleTrack> tracks) {
    _selectedSubtitleTracks = List.unmodifiable(
      {
        ..._selectedSubtitleTracks.where((track) => !_isSubtitleVisible(track)),
        ...tracks.where((track) =>
            _isSubtitleVisible(track) && _subtitleTracks.contains(track)),
      },
    );
    _notify();
  }

  Future<void> loadSubtitles(String text, {bool retry = false}) {
    setSubtitleSource(text);
    if (_disposed || _subtitleVideoId == null) return Future.value();
    if (_subtitleLoad case final pending?) return pending;
    if (_subtitlesLoaded || (_subtitleError != null && !retry)) {
      return Future.value();
    }
    final revision = _subtitleRevision;
    final url = YouTubeLink.parse(text).url;
    _subtitleError = null;
    final pending = _loadSubtitles(url, revision);
    _subtitleLoad = pending;
    _notify();
    return pending;
  }

  Future<void> _loadSubtitles(String url, int revision) async {
    try {
      final tracks = await _subtitleCatalog.load(url);
      if (_disposed || revision != _subtitleRevision) return;
      final sorted = [...tracks]..sort((a, b) {
          final kind = a.kind.index.compareTo(b.kind.index);
          return kind != 0 ? kind : a.label.compareTo(b.label);
        });
      _subtitleTracks = List.unmodifiable(sorted);
      _subtitlesLoaded = true;
      final english = sorted.where((track) =>
          track.kind == SubtitleKind.manual && track.languageCode == 'en');
      _selectedSubtitleTracks = List.unmodifiable(english.take(1));
    } catch (error) {
      if (_disposed || revision != _subtitleRevision) return;
      _subtitleError =
          'Could not load subtitle languages. Retry or turn Download subs off. ${_errorText(error)}';
    } finally {
      if (!_disposed && revision == _subtitleRevision) {
        _subtitleLoad = null;
        _notify();
      }
    }
  }

  final OutputFolderPreferences _outputPreferences = OutputFolderPreferences();
  late String _outputDirectory = defaultOutputDirectory;
  String? _outputPreferenceError;
  int _outputRevision = 0;
  int _saveRevision = 0;
  Future<void> _pendingOutputSave = Future<void>.value();

  String get outputDirectory => _outputDirectory;
  String? get outputPreferenceError => _outputPreferenceError;

  Future<void> restoreOutputDirectory() async {
    final revision = _outputRevision;
    try {
      final saved = await _outputPreferences.load();
      if (_disposed || revision != _outputRevision) return;
      if (saved != null && saved.isNotEmpty) _outputDirectory = saved;
      _outputPreferenceError = null;
    } catch (error) {
      if (_disposed || revision != _outputRevision) return;
      _outputPreferenceError =
          'Could not restore the output folder. Choose or type a folder to save it again. $error';
    }
    _notify();
  }

  void editOutputDirectory(String path) {
    _outputRevision++;
    _outputDirectory = path;
    commitOutputDirectory();
  }

  void commitOutputDirectory() {
    final path = _outputDirectory;
    if (_disposed) return;
    final revision = ++_saveRevision;
    _pendingOutputSave = _pendingOutputSave.then((_) async {
      try {
        await _outputPreferences.save(path);
        if (_disposed || revision != _saveRevision) return;
        _outputPreferenceError = null;
      } catch (error) {
        if (_disposed || revision != _saveRevision) return;
        _outputPreferenceError =
            'Could not remember the output folder. Your current folder is still usable. Check available disk space and app configuration permissions, then retry saving. $error';
      }
      _notify();
    });
  }

  final List<ClipJob> _jobs = [];
  final BundledTools _bundledTools = BundledTools();
  late final ClipPipeline _pipeline = ClipPipeline(_bundledTools);
  bool _processing = false;
  bool _disposed = false;
  int _nextId = 0;
  Timer? _cacheTimer;
  Future<void>? _cacheMaintenance;
  bool _cacheInitialized = false;
  String? _cacheError;

  bool get cacheBusy => _cacheMaintenance != null;
  bool get canClearCache => !_disposed && !_processing && !cacheBusy;
  String? get cacheError => _cacheError;

  Future<void> initializeCache() {
    if (_disposed || _cacheInitialized) {
      return _cacheMaintenance ?? Future<void>.value();
    }
    _cacheInitialized = true;
    _cacheTimer = Timer.periodic(const Duration(hours: 1), (_) {
      if (canClearCache) unawaited(_maintainCache(clear: false));
    });
    return _maintainCache(clear: false);
  }

  Future<bool> clearCache() async {
    if (!canClearCache) return false;
    await _maintainCache(clear: true);
    return !_disposed && _cacheError == null;
  }

  Future<void> _maintainCache({required bool clear}) {
    if (_disposed) return Future<void>.value();
    if (_cacheMaintenance case final pending?) return pending;
    final completion = Completer<void>();
    _cacheMaintenance = completion.future;
    _notify();
    unawaited(() async {
      try {
        if (clear) {
          await _pipeline.clearCache();
        } else {
          await _pipeline.pruneCache();
        }
        if (!_disposed) _cacheError = null;
      } catch (error) {
        if (!_disposed) {
          _cacheError =
              'Could not ${clear ? 'clear' : 'clean up'} temporary sources. Check temporary-folder permissions and free disk space, then retry Clear cache in Settings. ${_errorText(error)}';
        }
      } finally {
        _cacheMaintenance = null;
        completion.complete();
        _notify();
        if (!_disposed && !_processing) unawaited(_drain());
      }
    }());
    return completion.future;
  }

  List<ClipJob> get jobs => List.unmodifiable(_jobs);
  bool get isProcessing => _processing;
  String get defaultOutputDirectory {
    if (Platform.isLinux) return '';
    final home =
        Platform.environment[Platform.isWindows ? 'USERPROFILE' : 'HOME'];
    return p.join(home ?? Directory.current.path, 'Videos', 'YouTube Clips');
  }

  void add(ClipRequest request) {
    if (_disposed) return;
    _jobs.add(ClipJob(id: '${++_nextId}', request: request));
    _notify();
    unawaited(_drain());
  }

  void remove(ClipJob job) {
    if (_disposed || job.isActive) return;
    if (_jobs.remove(job)) _notify();
  }

  void clearFinished() {
    if (_disposed) return;
    _jobs.removeWhere((job) =>
        job.status == ClipJobStatus.completed ||
        job.status == ClipJobStatus.failed);
    _notify();
  }

  void retry(ClipJob job) {
    if (_disposed) return;
    if (!_jobs.contains(job) || job.status != ClipJobStatus.failed) return;
    job.status = ClipJobStatus.queued;
    job.progress = null;
    job.error = null;
    job.warning = null;
    job.outputPath = null;
    _notify();
    unawaited(_drain());
  }

  Future<void> _drain() async {
    if (_disposed || _processing || cacheBusy) return;
    if (!_cacheInitialized) {
      unawaited(initializeCache());
      return;
    }
    _processing = true;
    try {
      while (!_disposed) {
        final queued = _jobs.where((job) => job.status == ClipJobStatus.queued);
        if (queued.isEmpty) break;
        await _maintainCache(clear: false);
        if (_disposed) return;
        final remaining =
            _jobs.where((job) => job.status == ClipJobStatus.queued);
        if (remaining.isEmpty) break;
        final job = remaining.first;
        job.status = ClipJobStatus.downloading;
        _notify();
        try {
          final output = await _pipeline.run(
            job.request,
            onProgress: (cutting, progress) {
              if (_disposed) return;
              job.status =
                  cutting ? ClipJobStatus.cutting : ClipJobStatus.downloading;
              job.progress = progress;
              _notify();
            },
            onWarning: (warning) {
              if (_disposed) return;
              final combined =
                  [if (job.warning != null) job.warning!, warning].join('\n');
              job.warning = combined.length > 16384
                  ? combined.substring(combined.length - 16384)
                  : combined;
              _notify();
            },
          );
          if (_disposed) return;
          job.outputPath = output;
          job.progress = 1;
          job.status = ClipJobStatus.completed;
        } catch (error) {
          if (_disposed) return;
          job.error = _errorText(error);
          job.progress = null;
          job.status = ClipJobStatus.failed;
        }
        _notify();
      }
    } finally {
      _processing = false;
      _notify();
    }
  }

  void _notify() {
    if (!_disposed) notifyListeners();
  }

  @override
  void dispose() {
    if (_disposed) return;
    _disposed = true;
    _cacheTimer?.cancel();
    _subtitleCatalog.dispose();
    _pipeline.dispose();
    super.dispose();
  }
}

String _errorText(Object error) {
  final text = switch (error) {
    ProcessException() => '${error.executable}: ${error.message}',
    FileSystemException() =>
      '${error.message}${error.path == null ? '' : ': ${error.path}'}',
    FormatException() => error.message,
    _ => error.toString(),
  };
  return text.length > 16384 ? text.substring(text.length - 16384) : text;
}
